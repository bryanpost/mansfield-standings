"""Turn a shift's schedule CSVs into SQL for the Supabase SQL Editor.

Usage:
  py scripts/verify_schedule.py data/2026-27/wednesday-late
  py scripts/make_seed_sql.py --season 2026-27 --shift "Wednesday Late" \
      data/2026-27/wednesday-late > db/seed/2026-27/wednesday-late.sql

The SQL is safe to run more than once. Re-running refreshes team names, half
boundaries, dates, draw times and sheets, but NEVER overwrites a winner or a
draw-shot value that was entered through the site.
"""
import argparse
import csv
import sys
from pathlib import Path


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def read(folder, name):
    with open(Path(folder) / name, newline="") as f:
        return list(csv.DictReader(f))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("folder")
    ap.add_argument("--season", required=True)
    ap.add_argument("--shift", required=True)
    a = ap.parse_args()

    teams = read(a.folder, "teams.csv")
    games = read(a.folder, "games.csv")
    season, shift = q(a.season), q(a.shift)

    out = [
        f"-- Seed: {a.season} {a.shift}. Generated by scripts/make_seed_sql.py from {a.folder}/.",
        "-- Safe to re-run: never overwrites winners or draw shots entered through the site.",
        "begin;",
        "",
        "insert into public.teams (season, shift, team_no, name, first_half_end_week) values",
    ]
    out.append(",\n".join(
        f"  ({season}, {shift}, {int(t['team_no'])}, {q(t['name'])}, {int(t['first_half_end_week'])})" for t in teams))
    out.append("on conflict (season, shift, team_no) do update set")
    out.append("  name = excluded.name, first_half_end_week = excluded.first_half_end_week;")
    out.append("")
    out.append("insert into public.games (season, shift, week, game_date, draw_time, sheet, home_no, away_no, winner_no) values")
    rows = []
    for g in games:
        lo, hi = sorted((int(g["team_a"]), int(g["team_b"])))   # lower team number is stored as home_no
        win = g["winner_no"].strip() or "null"
        rows.append(f"  ({season}, {shift}, {int(g['week'])}, {q(g['date'])}, {q(g['draw'])}, {int(g['sheet'])}, {lo}, {hi}, {win})")
    out.append(",\n".join(rows))
    out.append("on conflict (season, shift, week, home_no, away_no) do update set")
    out.append("  game_date = excluded.game_date, draw_time = excluded.draw_time, sheet = excluded.sheet;")
    out.append("")
    out.append("commit;")
    out.append("")
    out.append("-- Check: expect "
               f"{len(teams)} teams and {len(games)} games for this shift.")
    out.append(f"select (select count(*) from public.teams where season = {season} and shift = {shift}) as teams,")
    out.append(f"       (select count(*) from public.games where season = {season} and shift = {shift}) as games;")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
